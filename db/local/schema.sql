-- Audit logging
------------------------------------------------------------------------------

CREATE TABLE audit_log_action (
  -- BY DEFAULT (not ALWAYS): seed data specifies explicit ids.
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 32 chars (raised from 16): UPDATE_DEVICE_CONFIG is 20.
  action_id varchar(32) NOT NULL UNIQUE,
  -- 64 chars (raised from 32): two seed labels are 35 and 39 chars.
  action_text varchar(64) NOT NULL
);

COMMENT ON TABLE audit_log_action IS 'The type of action a user performed on the system';
COMMENT ON COLUMN audit_log_action.action_id IS 'Stable machine key';
COMMENT ON COLUMN audit_log_action.action_text IS 'Human-readable label';

CREATE TABLE control_audit_log (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  date timestamptz NOT NULL DEFAULT now(),
  log_action_id int NOT NULL REFERENCES audit_log_action (id),
  device_id int NOT NULL REFERENCES device (id),
  actor_id text NOT NULL REFERENCES "user" (id)
);

CREATE INDEX idx_control_audit_log_date ON control_audit_log (date);
CREATE INDEX idx_control_audit_log_device_id ON control_audit_log (device_id);
CREATE INDEX idx_control_audit_log_actor_id ON control_audit_log (actor_id);

COMMENT ON TABLE control_audit_log IS 'Device control actions';
COMMENT ON COLUMN control_audit_log.date IS 'When the action occurred';
COMMENT ON COLUMN control_audit_log.log_action_id IS 'What action was performed';
COMMENT ON COLUMN control_audit_log.device_id IS 'The device acted upon';
COMMENT ON COLUMN control_audit_log.actor_id IS 'The user who performed the action';

CREATE TABLE user_audit_log (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  date timestamptz NOT NULL DEFAULT now(),
  log_action_id int NOT NULL REFERENCES audit_log_action (id),
  actor_id text NOT NULL REFERENCES "user" (id),
  target_id text NOT NULL REFERENCES "user" (id)
);

CREATE INDEX idx_user_audit_log_date ON user_audit_log (date);
CREATE INDEX idx_user_audit_log_actor_id ON user_audit_log (actor_id);
CREATE INDEX idx_user_audit_log_target_id ON user_audit_log (target_id);

COMMENT ON TABLE user_audit_log IS 'User management actions';
COMMENT ON COLUMN user_audit_log.date IS 'When the action occurred';
COMMENT ON COLUMN user_audit_log.log_action_id IS 'What action was performed';
COMMENT ON COLUMN user_audit_log.actor_id IS 'The user who performed the action';
COMMENT ON COLUMN user_audit_log.target_id IS 'The user the action was performed on';

CREATE TABLE roles_perms_audit_log (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  date timestamptz NOT NULL DEFAULT now(),
  log_action_id int NOT NULL REFERENCES audit_log_action (id),
  actor_id text NOT NULL REFERENCES "user" (id),
  -- role_id, permission_id, and added are nullable because not every action
  -- involves all three — CREATE_ROLE and DELETE_ROLE have a role but no
  -- permission.
  role_id int REFERENCES role (id),
  permission_id int REFERENCES permission (id),
  added boolean
);

CREATE INDEX idx_roles_perms_audit_log_date ON roles_perms_audit_log (date);
CREATE INDEX idx_roles_perms_audit_log_actor_id ON roles_perms_audit_log (actor_id);
CREATE INDEX idx_roles_perms_audit_log_role_id ON roles_perms_audit_log (role_id);

COMMENT ON TABLE roles_perms_audit_log IS 'Role and permission changes';
COMMENT ON COLUMN roles_perms_audit_log.date IS 'When the action occurred';
COMMENT ON COLUMN roles_perms_audit_log.log_action_id IS 'What action was performed';
COMMENT ON COLUMN roles_perms_audit_log.actor_id IS 'The user who performed the action';
COMMENT ON COLUMN roles_perms_audit_log.role_id IS 'The role affected';
COMMENT ON COLUMN roles_perms_audit_log.permission_id IS 'The permission affected';
COMMENT ON COLUMN roles_perms_audit_log.added IS 'TRUE if the permission was added, FALSE if removed';

