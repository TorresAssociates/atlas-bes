-- db/local/schema.sql — dev-only schema design scratchpad.
-- NOT the source of truth (that's the external migrations repo).
-- DROP-and-CREATE: running this destroys all local data.
--
-- Implements db/local/spec/schema-spec-users.md (users, auth, roles, permissions, audit).
-- Tables are created in the spec's dependency order — the file runs top to
-- bottom with no forward references. Seed data lives in seed.sql.

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

------------------------------------------------------------------------------
-- Tenancy: client, role
------------------------------------------------------------------------------

CREATE TABLE client (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name varchar(64) NOT NULL UNIQUE
);

COMMENT ON COLUMN client.id IS 'Unique identifier for each client';
COMMENT ON COLUMN client.name IS 'Name of the client';

CREATE TABLE role (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- Nullable deliberately (db/local/spec/schema-spec-users.md open item 1): a NULL may come to mean a
  -- global role; undecided.
  client_id int REFERENCES client (id)
);

CREATE INDEX idx_role_client_id ON role (client_id);

COMMENT ON COLUMN role.id IS 'Unique identifier for each role';
COMMENT ON COLUMN role.name IS 'Name of the role (clients may choose their own names)';
COMMENT ON COLUMN role.client_id IS 'The client this role belongs to. Nullable — see open items';

------------------------------------------------------------------------------
-- better-auth tables: "user", session, account, verification
--
-- ⚠ Generated by better-auth — config is the source of truth. Present here
-- only so codegen has types. Do not hand-edit to add columns — except the
-- "user" add-ons (phone_number, client_id, role_id), which are deliberate
-- extensions to better-auth's default user model.
--
-- "user" is a PostgreSQL reserved word and is double-quoted everywhere.
------------------------------------------------------------------------------

CREATE TABLE "user" (
  id text NOT NULL PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  email_verified boolean NOT NULL,
  image text,
  phone_number text,
  client_id int NOT NULL REFERENCES client (id),
  role_id int NOT NULL REFERENCES role (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL
);

CREATE INDEX idx_user_client_id ON "user" (client_id);
CREATE INDEX idx_user_role_id ON "user" (role_id);

COMMENT ON COLUMN "user".id IS 'Unique identifier for each user';
COMMENT ON COLUMN "user".name IS 'User''s chosen display name';
COMMENT ON COLUMN "user".email IS 'User''s email address for communication and login';
COMMENT ON COLUMN "user".email_verified IS 'Whether the user''s email is verified';
COMMENT ON COLUMN "user".image IS 'User''s image url';
COMMENT ON COLUMN "user".phone_number IS 'User''s phone number';
COMMENT ON COLUMN "user".client_id IS 'The client this user belongs to';
COMMENT ON COLUMN "user".role_id IS 'The user''s single role';
COMMENT ON COLUMN "user".created_at IS 'When the user account was created';
COMMENT ON COLUMN "user".updated_at IS 'Last update to the user''s information';

CREATE TABLE session (
  id text NOT NULL PRIMARY KEY,
  user_id text NOT NULL REFERENCES "user" (id),
  token text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  ip_address text,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL
);

-- Session lookup by token is covered by the UNIQUE constraint's index.
CREATE INDEX idx_session_user_id ON session (user_id);

COMMENT ON COLUMN session.id IS 'Unique identifier for each session';
COMMENT ON COLUMN session.user_id IS 'The ID of the user';
COMMENT ON COLUMN session.token IS 'The unique session token';
COMMENT ON COLUMN session.expires_at IS 'When the session expires';
COMMENT ON COLUMN session.ip_address IS 'The IP address of the device';
COMMENT ON COLUMN session.user_agent IS 'The user agent information of the device';
COMMENT ON COLUMN session.created_at IS 'When the session was created';
COMMENT ON COLUMN session.updated_at IS 'When the session was updated';

CREATE TABLE account (
  id text NOT NULL PRIMARY KEY,
  user_id text NOT NULL REFERENCES "user" (id),
  account_id text NOT NULL,
  provider_id text NOT NULL,
  access_token text,
  refresh_token text,
  access_token_expires_at timestamptz,
  refresh_token_expires_at timestamptz,
  scope text,
  id_token text,
  password text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL
);

CREATE INDEX idx_account_user_id ON account (user_id);

COMMENT ON COLUMN account.id IS 'Unique identifier for each account';
COMMENT ON COLUMN account.user_id IS 'The ID of the user';
COMMENT ON COLUMN account.account_id IS 'The ID of the account as provided by the SSO, or equal to user_id for credential accounts';
COMMENT ON COLUMN account.provider_id IS 'The ID of the provider';
COMMENT ON COLUMN account.access_token IS 'The access token of the account. Returned by the provider';
COMMENT ON COLUMN account.refresh_token IS 'The refresh token of the account. Returned by the provider';
COMMENT ON COLUMN account.access_token_expires_at IS 'When the access token expires';
COMMENT ON COLUMN account.refresh_token_expires_at IS 'When the refresh token expires';
COMMENT ON COLUMN account.scope IS 'The scope of the account. Returned by the provider';
COMMENT ON COLUMN account.id_token IS 'The ID token returned from the provider';
COMMENT ON COLUMN account.password IS 'The password of the account. Mainly used for email and password authentication';
COMMENT ON COLUMN account.created_at IS 'When the account was created';
COMMENT ON COLUMN account.updated_at IS 'When the account was updated';

CREATE TABLE verification (
  id text NOT NULL PRIMARY KEY,
  identifier text NOT NULL,
  value text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL
);

CREATE INDEX idx_verification_identifier ON verification (identifier);

COMMENT ON COLUMN verification.id IS 'Unique identifier for each verification';
COMMENT ON COLUMN verification.identifier IS 'The identifier for the verification request';
COMMENT ON COLUMN verification.value IS 'The value to be verified';
COMMENT ON COLUMN verification.expires_at IS 'When the verification request expires';
COMMENT ON COLUMN verification.created_at IS 'When the verification request was created';
COMMENT ON COLUMN verification.updated_at IS 'When the verification request was updated';

