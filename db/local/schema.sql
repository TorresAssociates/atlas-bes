-- Preferences
------------------------------------------------------------------------------

CREATE TABLE preference (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL UNIQUE REFERENCES "user" (id),
  -- map_style and theme stay text for now; possible future Postgres enums.
  -- Validate allowed values at the API boundary with TypeBox in the meantime.
  map_style text,
  layers_on_load jsonb,
  favorite jsonb,
  theme text,
  data_vis_preset jsonb
);

COMMENT ON COLUMN preference.id IS 'Unique identifier for each preference row';
COMMENT ON COLUMN preference.user_id IS 'The ID of the user. One preference row per user';
COMMENT ON COLUMN preference.map_style IS 'The style of map the user chooses to display on render';
COMMENT ON COLUMN preference.layers_on_load IS 'The layers the user wants to see on the map on load';
COMMENT ON COLUMN preference.favorite IS '(mobile) The favorites the user wants at the top of the bottom drawer menu';
COMMENT ON COLUMN preference.theme IS 'The theme of the app the user wants on load';
COMMENT ON COLUMN preference.data_vis_preset IS 'User presets for data visualizer graph';

------------------------------------------------------------------------------
-- Permissions
------------------------------------------------------------------------------

CREATE TABLE permission (
  -- BY DEFAULT (not ALWAYS): seed data specifies explicit ids.
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  description text NOT NULL,
  assign_role boolean NOT NULL
);

COMMENT ON COLUMN permission.id IS 'Unique identifier for a permission';
COMMENT ON COLUMN permission.name IS 'Name of the permission';
COMMENT ON COLUMN permission.description IS 'Description of what the permission does';
COMMENT ON COLUMN permission.assign_role IS 'Whether this permission may be attached to a role. false means it can only be granted to an individual user';

CREATE TABLE role_permission (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  role_id int NOT NULL REFERENCES role (id),
  permission_id int NOT NULL REFERENCES permission (id),
  UNIQUE (role_id, permission_id)
);

CREATE INDEX idx_role_permission_role_id ON role_permission (role_id);
CREATE INDEX idx_role_permission_permission_id ON role_permission (permission_id);

CREATE TABLE granted_permission (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  permission_id int NOT NULL REFERENCES permission (id),
  user_id text NOT NULL REFERENCES "user" (id),
  UNIQUE (user_id, permission_id)
);

CREATE INDEX idx_granted_permission_user_id ON granted_permission (user_id);
CREATE INDEX idx_granted_permission_permission_id ON granted_permission (permission_id);

COMMENT ON TABLE granted_permission IS 'Permissions granted to an individual user, outside their role';

------------------------------------------------------------------------------
-- Invitations
--
-- Flow: a client manager creates an invite, picking the role the new user
-- will receive → the invitee receives an email containing
-- https://<app>/invite?token=<token> → clicking it opens the signup page.
-- The invite carries the role, so signup assigns it directly.
------------------------------------------------------------------------------

CREATE TABLE invite (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  token uuid NOT NULL UNIQUE,
  expires_at timestamptz,
  sender_user_id text NOT NULL REFERENCES "user" (id),
  client_id int NOT NULL REFERENCES client (id),
  role_id int NOT NULL REFERENCES role (id)
);

-- token is already unique (index comes with the constraint).
CREATE INDEX idx_invite_sender_user_id ON invite (sender_user_id);
CREATE INDEX idx_invite_client_id ON invite (client_id);
CREATE INDEX idx_invite_role_id ON invite (role_id);

COMMENT ON COLUMN invite.id IS 'Unique identifier for invites';
COMMENT ON COLUMN invite.token IS 'uuid for the invite token url';
COMMENT ON COLUMN invite.expires_at IS 'When the invite token expires';
COMMENT ON COLUMN invite.sender_user_id IS 'The user who sent the invite';
COMMENT ON COLUMN invite.client_id IS 'The client the invitee will belong to';
COMMENT ON COLUMN invite.role_id IS 'The role the invited user will receive on signup';

-- Kept as a separate table for now.
CREATE TABLE accepted_invites (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  invite_id int NOT NULL REFERENCES invite (id),
  accepted_date timestamptz NOT NULL DEFAULT now(),
  user_id text NOT NULL REFERENCES "user" (id),
  UNIQUE (invite_id)
);

CREATE INDEX idx_accepted_invites_user_id ON accepted_invites (user_id);

COMMENT ON COLUMN accepted_invites.id IS 'Unique identifier for the acceptance record';
COMMENT ON COLUMN accepted_invites.invite_id IS 'The invite that was accepted';
COMMENT ON COLUMN accepted_invites.accepted_date IS 'When the invite was accepted';
COMMENT ON COLUMN accepted_invites.user_id IS 'The user created by accepting the invite';

